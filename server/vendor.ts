const FORMS: Array<[RegExp, string]> = [
  [/^общество\s+с\s+ограниченной\s+ответственностью\s+/i, 'ООО '],
  [/^публичное\s+акционерное\s+общество\s+/i, 'ПАО '],
  [/^закрытое\s+акционерное\s+общество\s+/i, 'ЗАО '],
  [/^открытое\s+акционерное\s+общество\s+/i, 'ОАО '],
  [/^акционерное\s+общество\s+/i, 'АО '],
  [/^индивидуальный\s+предприниматель\s+/i, 'ИП '],
];

/** «Общество с ограниченной ответственностью "СОФИЯ"» → «ООО «СОФИЯ»»: короче в реестре и отчётах. */
export function shortenVendor(name: string): string {
  let s = name.replace(/\s+/g, ' ').trim();
  for (const [re, short] of FORMS) s = s.replace(re, short);
  // Прямые кавычки вокруг названия → ёлочки
  return s.replace(/"([^"]+)"/g, '«$1»');
}
